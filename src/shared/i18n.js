// Look up a key. Falls back to English, then to the English text already in the
// markup, then to the key itself — a missing translation never blanks an element.
function translateMessage(language, key, fallback) {
	var dict = TRANSLATIONS[language] || TRANSLATIONS.en;
	return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}
